def apply(p, repo, log):
    src = repo / 'src' / 'tsundere'
    for f in sorted(src.iterdir()):
        if f.suffix in ('.h', '.cpp'):
            p.put_bytes(SF + 'tsundere/' + f.name, f.read_bytes())
    p.put_text(SF + 'tsundere/tsundere_secrets.h', secrets_header())
    p.put_text(SF + 'tsundere/tsundere_badges.h', badges_header(repo))
    log('tsundere sources added')
    patch_rc_manager(p)
    patch_helpers(p)
    patch_unread_badge(p)
    patch_profile_badge(p)
    patch_gradients(p)
    patch_profile_top_bar(p)
    log('features applied')
