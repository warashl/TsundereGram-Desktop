# TsundereGram Desktop: TsundereGram features on top of AyuGram Desktop.
# Badges, nickname gradients and profile banners from the same encrypted
# config the Android app reads (through the TsundereGram API).
import base64, hashlib, os, re

SF = 'Telegram/SourceFiles/'
INCLUDE = '#include "tsundere/tsundere.h"\n'


def c_array(name, data):
    rows = []
    for i in range(0, len(data), 20):
        rows.append('\t' + ','.join('0x%02x' % b for b in data[i:i + 20]) + ',')
    return 'constexpr unsigned char %s[] = {\n%s\n};\n' % (name, '\n'.join(rows))


def secrets_header():
    salt = os.environ.get('TSG_SALT', '').encode('utf-8')
    passphrase = os.environ.get('TSG_AES_KEY', '').encode('utf-8')
    if not salt or not passphrase:
        raise SystemExit('TSG_SALT / TSG_AES_KEY secrets are not set')
    # Stable mask, so the generated header does not change between builds.
    mask = hashlib.sha256(b'tsundere-mask:' + salt + b':' + passphrase).digest()[:16]
    def xor(data):
        return bytes(b ^ mask[i % len(mask)] for i, b in enumerate(data))
    return ('// Generated by scripts/features.py, do not edit.\n#pragma once\n\n'
            'namespace Tsundere::Secrets {\n\n'
            + c_array('kMask', mask) + '\n'
            + c_array('kSalt', xor(salt)) + '\n'
            + c_array('kPassphrase', xor(passphrase))
            + '\n} // namespace Tsundere::Secrets\n')


def badges_header(repo):
    def load(name):
        return base64.b64decode((repo / 'assets' / name).read_text().strip())
    return ('// Generated by scripts/features.py, do not edit.\n#pragma once\n\n'
            'namespace Tsundere::Badges {\n\n'
            + c_array('kDev', load('badge_dev.png.b64')) + '\n'
            + c_array('kLittle', load('badge_little.png.b64'))
            + '\n} // namespace Tsundere::Badges\n')


def once(p, rel, old, new):
    text = p.read(rel)
    if new in text and old not in text:
        return
    n = text.count(old)
    if n != 1:
        raise SystemExit('pattern found %d times in %s: %r' % (n, rel, old[:100]))
    p.write(rel, text.replace(old, new, 1))


def add_include(p, rel):
    text = p.read(rel)
    if INCLUDE in text:
        return
    m = re.search(r'^#include [<"][^>"\n]+[>"][^\n]*\n', text, flags=re.M)
    if not m:
        raise SystemExit('no #include in ' + rel)
    p.write(rel, text[:m.end()] + INCLUDE + text[m.end():])


