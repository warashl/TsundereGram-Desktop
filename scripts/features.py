def patch_profile_badge(p):
    rel = SF + 'info/profile/info_profile_badge.cpp'
    add_include(p, rel)
    text = p.read(rel)
    if 'Tsundere::PaintBadge' in text:
        return
    start = text.index('case BadgeType::ExteraSupporter: {')
    end = text.index('} break;', start)
    seg = text[start:end]
    old1 = '\t\t_view->paintRequest(\n'
    old2 = '\t\t\tPainter p(check);\n\t\t\tif (_overrideSt) {'
    if seg.count(old1) != 1 or seg.count(old2) != 1:
        raise SystemExit('unexpected Extera badge code in ' + rel)
    seg = seg.replace(old1,
        '\t\tconst auto tsgKind = (_content.badge == BadgeType::Extera)\n'
        '\t\t\t? Tsundere::BadgeKind::Dev\n'
        '\t\t\t: Tsundere::BadgeKind::Little;\n' + old1)
    seg = seg.replace(old2,
        '\t\t\tPainter p(check);\n'
        '\t\t\tif (Tsundere::PaintBadge(\n'
        '\t\t\t\t\tp,\n'
        '\t\t\t\t\ttsgKind,\n'
        '\t\t\t\t\tQRect(skip, 0, icon->width(), icon->height()))) {\n'
        '\t\t\t} else if (_overrideSt) {')
    p.write(rel, text[:start] + seg + text[end:])


